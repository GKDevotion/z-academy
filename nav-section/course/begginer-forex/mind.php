      <div class="sec-title">🧠 Trading Psychology — Master Your Mind</div>
      <p class="sec-desc">90% of retail traders lose money. The math is learnable — the mind is the real edge. Fear,
        greed and ego destroy more accounts than bad strategies ever will.</p>

      <div class="psych-card fear">
        <div class="psych-icon">😰</div>
        <div class="psych-title">Fear</div>
        <div class="psych-desc">Fear causes premature exits, missed entries and analysis paralysis. It stems from loss
          aversion — psychological research (Kahneman & Tversky, 1979) shows losses hurt approximately 2× more than
          equivalent gains feel good. This makes fearful traders exit winners too early and avoid valid setups after
          losses.</div>
        <div class="psych-tags">
          <span class="tag tb">Closing trades too early</span><span class="tag tb">Not pulling the trigger</span><span
            class="tag tb">Moving SL to break-even prematurely</span><span class="tag tb">Skipping valid setups after a
            loss</span><span class="tag tb">Over-analyzing to avoid deciding</span>
        </div>
        <div class="psych-fix"><strong>How to Fix It:</strong> Keep a trade journal — when you close early, note the
          outcome if you had held. Build statistical evidence that your edge works. Accept that losing trades are part
          of any profitable system, not personal failures. Reduce position size until fear disappears, then scale back
          up.</div>
      </div>

      <div class="psych-card greed">
        <div class="psych-icon">🤑</div>
        <div class="psych-title">Greed</div>
        <div class="psych-desc">Greed manifests as oversizing, moving take profit further mid-trade, removing stop
          losses, revenge trading after losses and FOMO (Fear Of Missing Out) entries. Greed is the #1 account killer —
          it temporarily works until one catastrophic trade wipes months of gains.</div>
        <div class="psych-tags">
          <span class="tag tr">Doubling lot size after big wins</span><span class="tag tr">Removing or moving Take
            Profit</span><span class="tag tr">FOMO entries mid-move</span><span class="tag tr">Revenge trading after
            losses</span><span class="tag tr">Adding to losing positions</span>
        </div>
        <div class="psych-fix"><strong>How to Fix It:</strong> Pre-define your TP before entering. Write it down. Stick
          to fixed % risk per trade regardless of how confident you feel. Implement a hard daily loss limit — when hit,
          shut the platform and step away. One bad session can erase a month of discipline.</div>
      </div>

      <div class="psych-card disc">
        <div class="psych-icon">⚔️</div>
        <div class="psych-title">Discipline</div>
        <div class="psych-desc">Discipline is the ability to follow your trading plan precisely — especially after
          losses or after big wins. Without discipline, you don't have a trading strategy; you have gambling. The
          hardest part: discipline feels most difficult exactly when it matters most.</div>
        <div class="psych-tags">
          <span class="tag tg">Written trading plan</span><span class="tag tg">Fixed rules for entries/exits</span><span
            class="tag tg">Max trades per day</span><span class="tag tg">Stop after 2 losses</span>
        </div>
        <div class="psych-fix"><strong>Building Discipline:</strong> 1. Write a specific trading plan with concrete
          entry/exit rules. 2. Only trade setups that perfectly match your plan. 3. Set a maximum of 3 trades per day —
          quality over quantity. 4. Walk away after 2 consecutive losses. Reset the next day with a clear mind.</div>
      </div>

      <div class="psych-card cons">
        <div class="psych-icon">📅</div>
        <div class="psych-title">Consistency</div>
        <div class="psych-desc">Professional traders don't chase big wins — they repeat the same process daily.
          Consistency is the compounding of discipline over time. A 1% monthly edge, repeated consistently, creates
          extraordinary wealth. Most traders fail because they abandon their system after 5 losing trades rather than
          trusting the statistical edge over 100+ trades.</div>
        <div class="psych-tags">
          <span class="tag tg">Daily trade journal</span><span class="tag tg">Same analysis routine</span><span
            class="tag tg">Weekly performance review</span><span class="tag tg">Sleep & rest schedule</span>
        </div>
        <div class="psych-fix"><strong>Consistency Framework:</strong> Keep a detailed trade journal (entry, exit,
          reason, emotion, result). Review every trade weekly — what patterns emerge? What time of day are your best
          trades? Which pairs suit your personality? Refine slowly. Never make drastic changes to a strategy after a few
          losing trades.</div>
      </div>
